"""Hyetograph, runoff the model makes (split by type), and the outlet hydrograph, with linear AND log y axes side by side.

WHAT IT MAKES (read-only: it only reads result files and writes pictures)
  One PNG per time window. Each PNG has two columns: LEFT = linear y axes, RIGHT = log y axes. Each column has three rows:
    1  hyetograph    rain the model used (basin mean, mm/h; hangs from the top)
    2  runoff made   runoff GENERATED on the land, all cells added (m3/s), split by runoff type
                     (linear: stacked colored areas; log: one line per type, because stacked areas cannot be drawn on a log axis)
    3  outlet        flow at the outlet: the gauge (black), the main run (colored), and the comparison run(s) (dashed)
  Also printed: for each window, the volume (million m3) generated by type, the outlet volume and the gauge volume.

THE SPLIT, AND WHAT IT CAN AND CANNOT SHOW
  tRIBS writes the runoff it generates in four types (the .rft file; columns in m3/s, all cells added, BEFORE routing):
      Hsrf    infiltration excess  (rain falls faster than the soil takes it)
      Sbsrf   subsurface stormflow (water coming out of the soil along the slope)
      Psrf    perched-water runoff
      Satsrf  saturation excess    (the soil is full)
  Their sum is Srf in the .mrf file. By default the picture shows two groups, Hsrf and "all other types" (Sbsrf + Psrf + Satsrf);
  use --split4 to draw all four.
  tRIBS does NOT write the outlet flow by type. Water from different hours and different types is mixed while it travels through the
  hillslopes and channels, so the outlet hydrograph cannot be honestly split. That is why the split is drawn in row 2 (runoff made)
  and the outlet is row 3. Compare the two rows by eye: the time between a runoff pulse in row 2 and its arrival in row 3 is the travel time.

RUN IT from workspaces/Sycamore/lab/ (nothing is run or changed):
    python plot_hydro_split_sycamore.py                              # windows flood and feb27, main run = Ks x1.03, comparison = draw 12 / k10 baseline
    python plot_hydro_split_sycamore.py --windows flood,feb27,tail   # more windows
    python plot_hydro_split_sycamore.py --compare none               # main run only
    python plot_hydro_split_sycamore.py --compare base,f0p15_as300   # several comparison runs (dashed; up to 3)
    python plot_hydro_split_sycamore.py --main f0p15_as300_ksx1p06   # another main run
    python plot_hydro_split_sycamore.py --windows custom --start "2017-01-20 00:00" --end "2017-01-23 00:00"
    python plot_hydro_split_sycamore.py --split4

WINDOWS (--windows, comma list):  flood = Jan 18-25;  jan23 = Jan 22 12:00 - Jan 25 12:00;  feb27 = Feb 27 - Mar 2;
  tail = Jan 25 - Feb 20;  season = the whole run (Oct 1 - Apr 1);  custom = use --start and --end.

RUN NAMES are the part of the file name after W4_d012_k10_ and before _nocl:
  base                     the draw 12 / k10 baseline (Ks x0.187, PsiB x0.2939, f x0.5874, As 1, cv 6.39, flowexp 0.2973, n 0.067)
  f0p15_as300_ksx1p03      f x0.15, As 300, Ks x1.03 (the working setting chosen 2026-11-02)
  f0p15_as300              the same without the Ks step;  f0p15_as300_ksx1p06 = Ks x1.06

FILES IT READS (change the folders with --results-dir and --obs-file)
  results/W4_d012_k10_<run>_nocl4368_00.mrf   hourly basin series: MAP_mm_hr (rain), Srf_m3_s
  results/W4_d012_k10_<run>_nocl4368_00.rft   hourly runoff by type: Hsrf_m3_s, Sbsrf_m3_s, Psrf_m3_s, Satsrf_m3_s
  results/W4_d012_k10_<run>_nocl_Outlet.qout  outlet flow
  ../init_data/obs/sycamore_09510200_obs_flow_WY2017.csv   the gauge

WORDS
  hyetograph   a bar chart of rain against time.        hydrograph   flow at one place against time.
  log axis     each gridline is 10 times the one below; it shows small flows (the tail) next to big ones (the flood).
  hour labels  the model files label an hour by its END (Time_hr 2736 = Jan 23 00:00 is the hour before it). Rain bars and runoff are
               drawn as the files give them (rain bars cover the hour ending at the label).
"""
import argparse
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.dates as mdates
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

PRE, SUF = "W4_d012_k10_", "_nocl"
T0 = pd.Timestamp("2016-10-01 00:00")
WINDOWS = {"flood": ("2017-01-18 00:00", "2017-01-25 00:00", "Flood week, Jan 18-25"),
           "jan23": ("2017-01-22 12:00", "2017-01-25 12:00", "Jan 23-24 event"),
           "feb27": ("2017-02-27 00:00", "2017-03-02 00:00", "Feb 27-28 storm"),
           "tail": ("2017-01-25 00:00", "2017-02-20 00:00", "After the flood (the tail)"),
           "season": ("2016-10-01 00:00", "2017-04-01 00:00", "Whole run, Oct 1 - Apr 1")}
NICE = {"base": "Draw 12 / k10 baseline", "f0p15_as300": "f x0.15, As 300, Ks x1.00", "f0p15_as300_ksx1p03": "f x0.15, As 300, Ks x1.03",
        "f0p15_as300_ksx1p06": "f x0.15, As 300, Ks x1.06", "f0p15_as300_ksx1p1": "f x0.15, As 300, Ks x1.10"}
C_MAIN, C_RAIN, C_GAUGE = "#2a78d6", "#7fb3e8", "black"
C_TYPE = {"Hsrf": "#eb6834", "Other": "#1baf7a", "Sbsrf": "#1baf7a", "Psrf": "#eda100", "Satsrf": "#7b4fc4"}
C_COMP = ["#444444", "#c43e7e", "#b8860b"]
TYPE_LABEL = {"Hsrf": "Hsrf  infiltration excess", "Other": "all other types (Sbsrf + Psrf + Satsrf)", "Sbsrf": "Sbsrf  subsurface stormflow",
              "Psrf": "Psrf  perched water", "Satsrf": "Satsrf  saturation excess"}

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("--main", default="f0p15_as300_ksx1p03", help="the main run (default: f x0.15, As 300, Ks x1.03)")
ap.add_argument("--compare", default="base", help="comma list of comparison runs, up to 3, or 'none' (default: base = draw 12 / k10)")
ap.add_argument("--windows", default="flood,feb27", help="comma list of: " + ", ".join(list(WINDOWS) + ["custom"]))
ap.add_argument("--start", default=None, help="with --windows custom: start, for example '2017-01-20 00:00'")
ap.add_argument("--end", default=None, help="with --windows custom: end")
ap.add_argument("--split4", action="store_true", help="draw all four runoff types instead of Hsrf and 'all other'")
ap.add_argument("--results-dir", default="results")
ap.add_argument("--obs-file", default="../init_data/obs/sycamore_09510200_obs_flow_WY2017.csv")
ap.add_argument("--out-dir", default="tail_figs")
ap.add_argument("--log-min", type=float, default=0.01, help="lowest value on the log axes, m3/s (default 0.01)")
ap.add_argument("--dpi", type=int, default=150)
args = ap.parse_args()

main_run = args.main.strip()
comps = [] if args.compare.strip().lower() in ("", "none") else [c.strip() for c in args.compare.split(",") if c.strip()]
if len(comps) > 3:
    sys.exit("Use at most 3 comparison runs.")
wins = [w.strip() for w in args.windows.split(",") if w.strip()]
bad = [w for w in wins if w not in WINDOWS and w != "custom"]
if bad or not wins:
    sys.exit(f"--windows must be a comma list of {', '.join(list(WINDOWS) + ['custom'])} (got {bad or 'nothing'}).")
if "custom" in wins and not (args.start and args.end):
    sys.exit("--windows custom needs --start and --end, for example --start '2017-01-20 00:00' --end '2017-01-23 00:00'.")
os.makedirs(args.out_dir, exist_ok=True)


def need(path):
    if not os.path.isfile(path):
        sys.exit(f"Cannot find {path}\nRun this from workspaces/Sycamore/lab/, check the run name (--main/--compare), or use --results-dir / --obs-file.")
    return path


def read_outlet(run):
    d = pd.read_csv(need(f"{args.results_dir}/{PRE}{run}{SUF}_Outlet.qout"))
    return pd.Series(d["Qstrm_m3_s"].to_numpy(float), index=T0 + pd.to_timedelta(d["Time_hr"].to_numpy(float), unit="h"))


def read_runoff(run):
    """Hourly basin rain and runoff by type (m3/s, all cells added). Index = hour END time, as the files label it."""
    stem = f"{args.results_dir}/{PRE}{run}{SUF}4368_00"
    m = pd.read_csv(need(stem + ".mrf"))
    f = pd.read_csv(need(stem + ".rft"))
    want_m, want_f = ["Time_hr", "MAP_mm_hr", "Srf_m3_s"], ["Time_hr", "Hsrf_m3_s", "Sbsrf_m3_s", "Psrf_m3_s", "Satsrf_m3_s"]
    for df, want, nm in ((m, want_m, ".mrf"), (f, want_f, ".rft")):
        miss = [c for c in want if c not in df.columns]
        if miss:
            sys.exit(f"The {nm} file of {run} has no column(s) {miss}. Columns found: {list(df.columns)}")
    d = m[want_m].merge(f[want_f], on="Time_hr")
    d.index = T0 + pd.to_timedelta(d["Time_hr"].to_numpy(float), unit="h")
    d["Other"] = d["Sbsrf_m3_s"] + d["Psrf_m3_s"] + d["Satsrf_m3_s"]
    return d


def name(run):
    return NICE.get(run, run)


def vol(series, lo, hi):
    """Volume in million m3 from m3/s values, hourly means summed over [lo, hi)."""
    s = series[(series.index >= pd.Timestamp(lo)) & (series.index < pd.Timestamp(hi))]
    return float(s.resample("1h").mean().sum() * 3600 / 1e6)


def logsafe(y):
    y = np.asarray(y, float).copy()
    y[y <= 0] = np.nan
    return y


obs = pd.read_csv(need(args.obs_file), parse_dates=["datetime"]).set_index("datetime")["q_cms"]
runoff = read_runoff(main_run)
outlet = {r: read_outlet(r) for r in [main_run] + comps}
types = ["Hsrf", "Sbsrf", "Psrf", "Satsrf"] if args.split4 else ["Hsrf", "Other"]
col = lambda t: f"{t}_m3_s" if t != "Other" else "Other"


def tidy(ax):
    ax.grid(alpha=0.25, which="major")
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)


written = []
for w in wins:
    a, b, title = (args.start, args.end, f"{args.start} to {args.end}") if w == "custom" else WINDOWS[w]
    a, b = pd.Timestamp(a), pd.Timestamp(b)
    span_h = (b - a) / pd.Timedelta(hours=1)
    fig, axes = plt.subplots(3, 2, figsize=(15, 9.5), sharex="col", gridspec_kw={"height_ratios": [0.8, 1.35, 2.0], "hspace": 0.08, "wspace": 0.2})
    rain = runoff["MAP_mm_hr"][a:b]
    rw = pd.Timedelta(minutes=54) if span_h <= 120 else pd.Timedelta(hours=1) * (span_h / 120.0)   # bar width: one hour, wider on long windows
    for j, scale in enumerate(("linear", "log")):
        ax_r, ax_g, ax_q = axes[0, j], axes[1, j], axes[2, j]
        # 1 hyetograph (rain; the same on both columns - rain is zero much of the time, which a log axis cannot show)
        ax_r.bar(rain.index - pd.Timedelta(minutes=30), rain.values, width=rw, color=C_RAIN)
        ax_r.invert_yaxis()
        ax_r.set_ylabel("Rain the model used\n(basin mean, mm/h)")
        # 2 runoff made
        g = runoff[a:b]
        if scale == "linear":
            ax_g.stackplot(g.index, *[g[col(t)].to_numpy() for t in types], colors=[C_TYPE[t] for t in types],
                           labels=[TYPE_LABEL[t] for t in types], linewidth=0)
            ax_g.set_ylim(bottom=0)
        else:
            for t in types:
                ax_g.plot(g.index, logsafe(g[col(t)]), color=C_TYPE[t], lw=1.5, label=TYPE_LABEL[t])
            ax_g.plot(g.index, logsafe(g["Srf_m3_s"]), color="#222222", lw=1.0, ls=":", label="total (Srf)")
            ax_g.set_yscale("log")
            top = np.nanmax(logsafe(g["Srf_m3_s"])) if np.isfinite(logsafe(g["Srf_m3_s"])).any() else 1.0
            ax_g.set_ylim(args.log_min, max(top * 3, args.log_min * 100))
        ax_g.set_ylabel("Runoff made on the land\n(all cells added, m$^3$/s)")
        ax_g.legend(frameon=False, fontsize=8, loc="upper right")
        # 3 outlet
        ax_q.plot(obs[a:b].index, logsafe(obs[a:b].values) if scale == "log" else obs[a:b].values, color=C_GAUGE, lw=2.2, label="Gauge 09510200 (observed)")
        for r, c in zip(comps, C_COMP):
            q = outlet[r][a:b]
            ax_q.plot(q.index, logsafe(q.values) if scale == "log" else q.values, color=c, lw=1.5, ls="--", label=name(r))
        q = outlet[main_run][a:b]
        ax_q.plot(q.index, logsafe(q.values) if scale == "log" else q.values, color=C_MAIN, lw=1.9, label=name(main_run))
        if scale == "log":
            ax_q.set_yscale("log")
            tops = [np.nanmax(logsafe(x[a:b].values)) for x in [obs] + list(outlet.values()) if np.isfinite(logsafe(x[a:b].values)).any()]
            ax_q.set_ylim(args.log_min, max(max(tops) * 3 if tops else 1.0, args.log_min * 100))
            ax_q.axhspan(0.3, 1.0, color="#8a8984", alpha=0.15, lw=0)
            ax_q.text(0.005, 0.3 * 0.9, "gauge slow-flow band 0.3-1 m$^3$/s", transform=ax_q.get_yaxis_transform(), ha="left", va="top", fontsize=7, color="#555555")
        else:
            ax_q.set_ylim(bottom=0)
        ax_q.set_ylabel("Flow at the outlet (m$^3$/s)")
        ax_q.legend(frameon=False, fontsize=8, loc="upper right")
        ax_q.set_xlabel("Phoenix time (MST)")
        loc = mdates.AutoDateLocator()
        ax_q.xaxis.set_major_locator(loc)
        ax_q.xaxis.set_major_formatter(mdates.ConciseDateFormatter(loc))
        for ax in (ax_r, ax_g, ax_q):
            tidy(ax)
        axes[0, j].set_title(f"{'Linear' if scale == 'linear' else 'Log'} y axes", loc="left", fontsize=10, color="#555555")
    fig.suptitle(f"{title}: rain, runoff made (by type) and outlet flow. Main run: {name(main_run)}", x=0.01, ha="left", fontsize=12)
    fn = os.path.join(args.out_dir, f"fig_split_{w}_{main_run}.png")
    fig.savefig(fn, dpi=args.dpi, bbox_inches="tight")
    plt.close(fig)
    written.append(fn)

    # volumes for this window
    r = runoff
    gen = {t: vol(r[col(t)], a, b) for t in ["Hsrf", "Sbsrf", "Psrf", "Satsrf"]}
    tot = vol(r["Srf_m3_s"], a, b)
    rain_mm = float(rain.sum())
    print(f"\n{title}  ({a:%b %d %H:%M} to {b:%b %d %H:%M})   volumes in million m3")
    print(f"  rain the model used (basin mean) {rain_mm:.1f} mm")
    print(f"  runoff made, main run: total {tot:.2f}  =  Hsrf {gen['Hsrf']:.2f} ({100 * gen['Hsrf'] / tot:.0f}%)  + Sbsrf {gen['Sbsrf']:.2f}  + Psrf {gen['Psrf']:.2f}  + Satsrf {gen['Satsrf']:.2f}"
          if tot > 0 else "  runoff made, main run: none in this window")
    print(f"  outlet: gauge {vol(obs, a, b):.2f}   " + "   ".join(f"{name(x)} {vol(outlet[x], a, b):.2f}" for x in [main_run] + comps))
    print("  (outlet volumes include flow that was already there before the rain; runoff made is before routing)")

print("\nWrote:\n  " + "\n  ".join(written))
